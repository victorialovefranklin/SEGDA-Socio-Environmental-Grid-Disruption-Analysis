def build_tract_ejbi(paths):
    ces = pd.read_csv(paths["ces"], low_memory=False)
    svi = pd.read_csv(paths["svi_tract"], low_memory=False)
    tracts = gpd.read_file(paths["tract_shp"])[["GEOID", "geometry"]].copy()
    tracts["GEOID"] = tracts["GEOID"].astype(str).str.zfill(11)

    cx = pd.DataFrame({
        "GEOID": ces["Tract"].astype(str).str.replace(r"\.0$", "", regex=True).str.zfill(11),
        "population": pd.to_numeric(ces["Population"], errors="coerce"),
        "CES": pd.to_numeric(ces["CIscoreP"], errors="coerce") / 100.0,
        "Pollution": pd.to_numeric(ces["Pollution_Pctl"], errors="coerce") / 100.0,
    }).drop_duplicates("GEOID")

    sx = pd.DataFrame({
        "GEOID": svi["FIPS"].astype(str).str.replace(r"\.0$", "", regex=True).str.zfill(11),
        "SVI": pd.to_numeric(svi["RPL_THEMES"], errors="coerce"),
    }).drop_duplicates("GEOID")
    sx.loc[sx["SVI"] < 0, "SVI"] = np.nan

    t = tracts.merge(cx, on="GEOID", how="left").merge(sx, on="GEOID", how="left")
    t["components_present"] = t[["SVI", "CES", "Pollution"]].notna().sum(axis=1)
    t["EJBI"] = t[["SVI", "CES", "Pollution"]].mean(axis=1, skipna=False)
    t["county_fips"] = t["GEOID"].str[:5]
    t["High_EJBI_tract"] = pd.Series(pd.NA, index=t.index, dtype="Int64")
    ok = t["EJBI"].notna()
    t.loc[ok, "High_EJBI_tract"] = (t.loc[ok, "EJBI"] >= TRACT_HIGH_EJBI_THRESHOLD).astype(int)

    # Explicit percentile-rank sensitivity; never silently substituted for numeric EJBI.
    t["EJBI_percentile_rank"] = np.nan
    t.loc[ok, "EJBI_percentile_rank"] = t.loc[ok, "EJBI"].rank(method="average", pct=True)

    return t

def build_county_ejbi(tracts, paths):
    valid = tracts.dropna(subset=["EJBI"]).copy()
    valid["weight"] = valid["population"].fillna(1)

    def agg(g):
        if g["weight"].sum() > 0:
            score = np.average(g["EJBI"], weights=g["weight"])
        else:
            score = g["EJBI"].mean()
        return pd.Series({
            "EJBI": score,
            "n_valid_tracts": len(g),
            "n_high_ejbi_tracts": int((g["EJBI"] >= TRACT_HIGH_EJBI_THRESHOLD).sum()),
            "county_population": g["population"].sum(),
        })

    county = valid.groupby("county_fips").apply(agg, include_groups=False).reset_index()

    cg = gpd.read_file(paths["county_shp"]).copy()
    # California FIPS filtering for national county shapefile.
    state_col = "STATEFP" if "STATEFP" in cg.columns else None
    if state_col:
        cg = cg[cg[state_col].astype(str).str.zfill(2) == "06"].copy()

    # Geometry QA: spatial statistics require a complete, valid 58-county layer.
    if len(cg) != 58:
        raise ValueError(
            f"County shapefile QA failed: expected 58 California counties, found {len(cg)}. "
            "Use the complete 2019 TIGER/Line county shapefile bundle."
        )
    missing_geom = cg.geometry.isna()
    empty_geom = cg.geometry.apply(lambda geom: geom is not None and geom.is_empty)
    if bool((missing_geom | empty_geom).any()):
        bad_names = []
        if "NAME" in cg.columns:
            bad_names = cg.loc[missing_geom | empty_geom, "NAME"].astype(str).tolist()
        raise ValueError(
            "County shapefile QA failed: missing/empty geometry detected"
            + (f" for: {', '.join(bad_names)}" if bad_names else "")
            + ". Make sure .shp, .shx, .dbf, .prj, and .cpg files are together."
        )

    invalid_geom = ~cg.geometry.is_valid
    if bool(invalid_geom.any()):
        try:
            cg.loc[invalid_geom, "geometry"] = cg.loc[invalid_geom, "geometry"].make_valid()
        except Exception:
            cg.loc[invalid_geom, "geometry"] = cg.loc[invalid_geom, "geometry"].buffer(0)

    if "GEOID" in cg.columns:
        cg["county_fips"] = cg["GEOID"].astype(str).str.zfill(5)
    elif {"STATEFP","COUNTYFP"}.issubset(cg.columns):
        cg["county_fips"] = cg["STATEFP"].astype(str).str.zfill(2) + cg["COUNTYFP"].astype(str).str.zfill(3)
    else:
        raise ValueError("County shapefile lacks usable FIPS fields.")

    name_col = "NAME" if "NAME" in cg.columns else None
    keep = ["county_fips", "geometry"] + ([name_col] if name_col else [])
    cg = cg[keep].copy()
    if name_col:
        cg = cg.rename(columns={name_col: "county"})
    county = cg.merge(county, on="county_fips", how="left")
    county["High_EJBI_county"] = (county["EJBI"] >= COUNTY_HIGH_EJBI_THRESHOLD).astype("Int64")
    return county

def clean_eaglei_episodes(paths):
    e = pd.read_csv(paths["eaglei_transformed"], low_memory=False)

    required = ["fips","state","county","start_time","duration","min_customers","max_customers","mean_customers"]
    missing = [c for c in required if c not in e.columns]
    if missing:
        raise ValueError(f"Transformed EAGLE-I missing required episode fields: {missing}")

    e["start_time"] = pd.to_datetime(e["start_time"], errors="coerce", utc=True)
    if "end_time" in e.columns:
        e["end_time"] = pd.to_datetime(e["end_time"], errors="coerce", utc=True)

    for c in ["fips","duration","min_customers","max_customers","mean_customers"]:
        e[c] = pd.to_numeric(e[c], errors="coerce")

    episode_key = required.copy()
    multiplicity = e.groupby(episode_key, dropna=False).size().reset_index(name="source_row_multiplicity")

    # Prefer a row without OE-417 linkage when a duplicate group contains one.
    oe_cols = [c for c in ["event_id","state_event","Datetime Event Began","Datetime Restoration","Event Type"] if c in e.columns]
    e["_has_oe417"] = e[oe_cols].notna().any(axis=1) if oe_cols else False
    e = e.sort_values(episode_key + ["_has_oe417"], ascending=[True]*len(episode_key)+[True], kind="stable")
    e = e.drop_duplicates(subset=episode_key, keep="first").copy()
    e = e.merge(multiplicity, on=episode_key, how="left", validate="one_to_one")
    e.drop(columns=["_has_oe417"], inplace=True, errors="ignore")

    e["year"] = e["start_time"].dt.year
    e = e[e["year"].between(STUDY_START, STUDY_END)].copy()
    e["county_fips"] = pd.to_numeric(e["fips"], errors="coerce").astype("Int64").astype(str).str.zfill(5)
    e["estimated_customer_outage_hours"] = e["mean_customers"] * e["duration"]

    # QA flags preserve known transformation artifacts rather than "correcting" unknown upstream choices.
    e["qa_min_customers_at_200"] = np.isclose(e["min_customers"], 200, equal_nan=False)
    e["qa_duration_at_34h"] = np.isclose(e["duration"], 34, equal_nan=False)
    max_ceiling = e["max_customers"].max(skipna=True)
    e["qa_max_customers_at_dataset_ceiling"] = np.isclose(e["max_customers"], max_ceiling, equal_nan=False)

    return e

def build_outage_burden(episodes, paths):
    burden = episodes.groupby("county_fips", as_index=False).agg(
        estimated_customer_outage_hours=("estimated_customer_outage_hours","sum"),
        reconstructed_episodes=("county_fips","size"),
        episodes_at_200_floor=("qa_min_customers_at_200","sum"),
        episodes_at_34h_ceiling=("qa_duration_at_34h","sum"),
        max_prior_join_multiplicity=("source_row_multiplicity","max"),
    )

    unc = episodes[~episodes["qa_duration_at_34h"]].groupby(
        "county_fips", as_index=False
    )["estimated_customer_outage_hours"].sum().rename(
        columns={"estimated_customer_outage_hours":"estimated_coh_excl34"}
    )
    burden = burden.merge(unc, on="county_fips", how="left")

    mcc = pd.read_csv(paths["mcc"], low_memory=False)
    mcc["county_fips"] = mcc["County_FIPS"].astype(str).str.replace(r"\.0$", "", regex=True).str.zfill(5)
    mcc["modeled_customers"] = pd.to_numeric(mcc["Customers"], errors="coerce")
    mcc = mcc[mcc["county_fips"].str.startswith("06")].groupby(
        "county_fips", as_index=False
    )["modeled_customers"].sum()

    burden = burden.merge(mcc, on="county_fips", how="left")
    burden["coh_per_mcc"] = burden["estimated_customer_outage_hours"] / burden["modeled_customers"]
    burden["OBI_MCC"] = robust_norm_iqr(burden["coh_per_mcc"])
    burden["coh_per_mcc_excl34"] = burden["estimated_coh_excl34"] / burden["modeled_customers"]
    burden["OBI_MCC_EXCL34"] = robust_norm_iqr(burden["coh_per_mcc_excl34"])
    return burden

def build_climate(paths):
    n = pd.read_csv(paths["nri"], low_memory=False)
    n["county_fips"] = n["STCOFIPS"].astype(str).str.replace(r"\.0$", "", regex=True).str.zfill(5)
    hazard_map = {
        "DRGT_RISKS":"drought",
        "HWAV_RISKS":"heat",
        "WFIR_RISKS":"wildfire",
        "RFLD_RISKS":"flood",
        "ERQK_RISKS":"earthquake",
        "SWND_RISKS":"wind",
        "TRND_RISKS":"tornado",
    }
    norm_cols = []
    for source, label in hazard_map.items():
        if source not in n.columns:
            raise ValueError(f"NRI missing required field: {source}")
        col = f"{label}_norm"
        n[col] = minmax(n[source])
        norm_cols.append(col)
    n["Climate_Stress"] = n[norm_cols].mean(axis=1, skipna=True)
    return n[["county_fips","Climate_Stress"] + norm_cols].drop_duplicates("county_fips")

def combine_metrics(county_gdf, burden, climate):
    d = county_gdf.merge(burden, on="county_fips", how="left").merge(climate, on="county_fips", how="left")
    d["coh_per_population"] = d["estimated_customer_outage_hours"] / d["county_population"]
    d["OBI_POP"] = robust_norm_iqr(d["coh_per_population"])
    return d


def attach_eia_historical_sensitivity(counties, paths):
    """
    Join the independently audited 2018-2023 EIA reliability summary.

    The source summary already applies:
      - annual utility-to-county allocation using service-territory constraints,
        annual utility customers, and MCC county totals via IPF/RAS;
      - >=80% SAIDI-reporting customer-mass threshold for county-year inclusion;
      - >=4 qualifying years for the six-year reliability index.

    EIA is sensitivity-only in v7.1.
    """
    eia = pd.read_csv(paths["eia_historical_summary"], low_memory=False)
    keep = [
        "county", "years_with_ge80_coverage", "mean_saidi_2018_2023",
        "median_saidi_2018_2023", "mean_saifi_2018_2023",
        "mean_reporting_coverage_pct", "EIA_RELIABILITY_INDEX_2018_2023"
    ]
    missing = [c for c in keep if c not in eia.columns]
    if missing:
        raise ValueError(f"Historical EIA summary missing required columns: {missing}")

    d = counties.merge(eia[keep], on="county", how="left")

    # Sensitivity branches; 70/30 mirrors the submitted study design but is not primary.
    d["OBI_EIA20"] = 0.80*d["OBI_MCC"] + 0.20*d["EIA_RELIABILITY_INDEX_2018_2023"]
    d["OBI_EIA30"] = 0.70*d["OBI_MCC"] + 0.30*d["EIA_RELIABILITY_INDEX_2018_2023"]
    d["OBI_EIA50"] = 0.50*d["OBI_MCC"] + 0.50*d["EIA_RELIABILITY_INDEX_2018_2023"]
    return d

def correlation_row(df, x, y):
    z = df[[x,y]].dropna()
    r,p = stats.pearsonr(z[x], z[y])
    rho,ps = stats.spearmanr(z[x], z[y])
    return {
        "Variable_1":x, "Variable_2":y, "N":len(z),
        "Pearson_r":r, "Pearson_p":p,
        "Spearman_rho":rho, "Spearman_p":ps,
    }


def bootstrap_corr(df, x, y, nboot=5000, seed=42):
    z = df[[x,y]].dropna().reset_index(drop=True)
    r,p = stats.pearsonr(z[x],z[y])
    rng = np.random.default_rng(seed)
    vals = []
    for _ in range(nboot):
        idx = rng.integers(0, len(z), len(z))
        b = z.iloc[idx]
        if b[x].nunique() > 1 and b[y].nunique() > 1:
            vals.append(stats.pearsonr(b[x],b[y])[0])
    lo,hi = np.quantile(vals,[0.025,0.975])
    return len(z),r,p,lo,hi

