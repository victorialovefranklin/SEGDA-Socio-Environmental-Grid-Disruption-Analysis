def finalize_export_bundle():
    """
    Create a complete downloadable ZIP after every successful run.
    The ZIP is placed beside the output directory, not inside it.
    """
    # Copy top-level result files into export_bundle/results for a single clean bundle view.
    bundle_results = EXPORT_DIR / "data_and_results"
    bundle_results.mkdir(parents=True, exist_ok=True)

    for p in OUT.iterdir():
        if p.is_file() and p.suffix.lower() in {".csv", ".json", ".txt"}:
            shutil.copy2(p, bundle_results / p.name)

    # Copy organized directories into export bundle.
    for name, source in [
        ("tables", TABLE_DIR),
        ("validation", VALIDATION_DIR),
        ("data_products", DATA_DIR),
        ("results", RESULTS_DIR),
        ("manifests", MANIFEST_DIR),
    ]:
        target = EXPORT_DIR / name
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(source, target)

    # Figures stay in their existing high-resolution folders and are also copied into the bundle.
    target_fig = EXPORT_DIR / "figures"
    if target_fig.exists():
        shutil.rmtree(target_fig)
    shutil.copytree(FIG, target_fig)

    zip_base = OUT.parent / OUT.name
    zip_path = Path(shutil.make_archive(str(zip_base), "zip", root_dir=OUT))

    if not zip_path.exists() or zip_path.stat().st_size == 0:
        raise IOError(f"ZIP export failed: {zip_path}")

    return zip_path


