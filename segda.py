def build_queen_weights(county_gdf):
    """
    Build row-standardized Queen-contiguity weights with explicit geometry QA.

    v7.6.6 fix:
    Prevents the prior AttributeError: 'NoneType' object has no attribute 'touches'
    by validating every county geometry before any spatial predicate is evaluated.
    """
    if not isinstance(county_gdf, gpd.GeoDataFrame):
        raise TypeError("Queen weights require a GeoDataFrame.")
    if "geometry" not in county_gdf.columns:
        raise ValueError("Queen weights require a geometry column.")

    g = county_gdf.reset_index(drop=True).copy()

    missing = g.geometry.isna()
    empty = g.geometry.apply(lambda geom: geom is not None and geom.is_empty)
    bad = missing | empty
    if bool(bad.any()):
        cols = [c for c in ["county_fips", "county"] if c in g.columns]
        bad_rows = g.loc[bad, cols]
        detail = bad_rows.to_string(index=False) if len(cols) else str(list(g.index[bad]))
        raise ValueError(
            "County geometry QA failed before Queen-contiguity calculation. "
            f"Missing/empty geometries: {int(bad.sum())}\n{detail}\n"
            "Do not drop these counties. Re-extract the complete TIGER/Line county "
            "shapefile (.shp + .shx + .dbf + .prj + .cpg) and rerun."
        )

    invalid = ~g.geometry.is_valid
    if bool(invalid.any()):
        try:
            g.loc[invalid, "geometry"] = g.loc[invalid, "geometry"].make_valid()
        except Exception:
            g.loc[invalid, "geometry"] = g.loc[invalid, "geometry"].buffer(0)

    still_bad = g.geometry.isna() | g.geometry.apply(
        lambda geom: geom is None or geom.is_empty or (not geom.is_valid)
    )
    if bool(still_bad.any()):
        raise ValueError("County geometry repair failed; spatial analysis cannot proceed safely.")

    n = len(g)
    A = np.zeros((n, n), dtype=float)

    for i in range(n):
        gi = g.geometry.iloc[i]
        for j in range(i + 1, n):
            gj = g.geometry.iloc[j]
            if gi.touches(gj):
                A[i, j] = 1.0
                A[j, i] = 1.0

    rs = A.sum(axis=1)
    islands = np.where(rs == 0)[0]
    if len(islands):
        cols = [c for c in ["county_fips", "county"] if c in g.columns]
        detail = g.iloc[islands][cols].to_string(index=False) if cols else str(islands.tolist())
        raise ValueError(
            "Queen-contiguity QA failed: one or more counties have no neighbors.\n"
            f"{detail}\nCheck the county boundary files before computing Moran's I/LISA."
        )

    W = np.divide(A, rs[:, None], out=np.zeros_like(A), where=rs[:, None] > 0)
    return A, W

def global_moran_permutation(x,W,perms=999,seed=42):
    x=np.asarray(x,float); z=x-x.mean(); n=len(x); S0=W.sum()
    I=n/S0*(z@W@z)/(z@z)
    rng=np.random.default_rng(seed)
    sim=np.empty(perms)
    for k in range(perms):
        zp=rng.permutation(z)
        sim[k]=n/S0*(zp@W@zp)/(zp@zp)
    center=sim.mean()
    p=(np.sum(np.abs(sim-center)>=abs(I-center))+1)/(perms+1)
    zscore=(I-sim.mean())/sim.std(ddof=1)
    return I,zscore,p

def local_moran_permutation(x,W,perms=999,seed=42):
    x=np.asarray(x,float)
    z=(x-x.mean())/x.std(ddof=0)
    m2=(z@z)/len(z); lag=W@z; Ii=z*lag/m2
    rng=np.random.default_rng(seed); sim=np.zeros((perms,len(z)))
    for k in range(perms):
        zp=rng.permutation(z)
        sim[k]=zp*(W@zp)/((zp@zp)/len(z))
    center=sim.mean(axis=0)
    p=(np.sum(np.abs(sim-center)>=np.abs(Ii-center),axis=0)+1)/(perms+1)
    quad=np.full(len(z),"NS",dtype=object); sig=p<.05
    quad[sig&(z>0)&(lag>0)]="HH"; quad[sig&(z<0)&(lag<0)]="LL"
    quad[sig&(z>0)&(lag<0)]="HL"; quad[sig&(z<0)&(lag>0)]="LH"
    return Ii,p,quad

def spatial_diagnostics(counties):
    A,_=build_queen_weights(counties)
    summaries=[]; locals_all=[]
    for metric in ["EJBI","OBI_MCC","OBI_EIA30"]:
        sub=counties[counties[metric].notna()].copy()
        idx=sub.index.to_numpy()
        As=A[np.ix_(idx,idx)]
        rs=As.sum(axis=1)
        Ws=np.divide(As,rs[:,None],out=np.zeros_like(As),where=rs[:,None]>0)
        I,z,p=global_moran_permutation(sub[metric].to_numpy(),Ws)
        Ii,lp,quad=local_moran_permutation(sub[metric].to_numpy(),Ws)
        counts=pd.Series(quad).value_counts()
        summaries.append([metric,len(sub),I,z,p,int(counts.get("HH",0)),int(counts.get("LL",0)),
                          int(counts.get("HL",0)),int(counts.get("LH",0)),int(counts.get("NS",0))])
        loc=sub[["county_fips","county",metric]].copy()
        loc["local_I"]=Ii; loc["pseudo_p"]=lp; loc["cluster"]=quad; loc["metric"]=metric
        locals_all.append(loc)
    return (
        pd.DataFrame(summaries,columns=["metric","N","Moran_I","permutation_z","pseudo_p","HH","LL","HL","LH","NS"]),
        pd.concat(locals_all,ignore_index=True)
    )

